// Current Selection
let currentVideoCategory = null;
let currentVideoType = null;

// Open Category
function openCategory(category) {
  currentVideoCategory = category;
  
  // Hide landing page, show video type selection
  document.getElementById('videosLanding').style.display = 'none';
  document.getElementById('videoTypeSelection').style.display = 'block';
  
  // Set category title
  const categoryData = videoData[category];
  document.getElementById('categoryTitleType').textContent = `${categoryData.icon} ${categoryData.title} Videos`;
  
  window.scrollTo(0, 0);
}

// Load Video List
function loadVideoList(videoType) {
  currentVideoType = videoType;
  
  if (!currentVideoCategory) return;
  
  const categoryData = videoData[currentVideoCategory];
  const videos = categoryData[videoType];
  
  // Hide video type selection, show video list
  document.getElementById('videoTypeSelection').style.display = 'none';
  document.getElementById('videoListDisplay').style.display = 'block';
  
  // Set title
  const typeLabel = videoType === 'long' ? 'Detailed Videos' : 'Quick Overview Videos';
  document.getElementById('videoListTitle').textContent = `${typeLabel} - ${categoryData.title}`;
  
  // Populate video list
  const container = document.getElementById('videoListContainer');
  container.innerHTML = '';
  
  videos.forEach((video, index) => {
    const videoCard = document.createElement('div');
    videoCard.className = 'video-item-card';
    videoCard.innerHTML = `
      <span class="video-item-number">Video ${index + 1}</span>
      <h3>${video.title}</h3>
      <p>${video.description}</p>
      <div class="video-item-duration"><i class="fa-solid fa-clock"></i> ${video.duration}</div>
    `;
    videoCard.onclick = () => playVideo(video, videoType);
    container.appendChild(videoCard);
  });
  
  window.scrollTo(0, 0);
}

// Play Video
