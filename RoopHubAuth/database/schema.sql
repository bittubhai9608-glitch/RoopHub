CREATE TABLE ROOPHUB_CUSTOMERS (
    CUSTOMER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(80 CHAR) NOT NULL,
    EMAIL VARCHAR2(254 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(512 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_ROOPHUB_CUSTOMER_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE ROOPHUB_PENDING_SIGNUPS (
    EMAIL VARCHAR2(254 CHAR) PRIMARY KEY,
    FULL_NAME VARCHAR2(80 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(512 CHAR) NOT NULL,
    OTP_HASH VARCHAR2(64 CHAR) NOT NULL,
    ATTEMPTS NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL
);

